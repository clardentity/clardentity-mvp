#: What one generated picture counts as against a visitor's allowance. Half
#: of it: a guest can see Co-Creative draw, and cannot run up an image bill.
_IMAGE_CHARGE_TOKENS = 2_500
#: Held against the address and the day before a turn runs (guest_demo.reserve).
_RESERVE_TOKENS = 10_000


def _conversation_tokens(output_tokens: int, message: str, turns: list[dict]) -> int:
    """What a turn costs the visitor: the conversation, not the apparatus.

    The allowance is 5,000 tokens of conversation - what the visitor wrote
    and what came back. It is not the web excerpts fetched to ground the
    answer (about 3,500 tokens of input on a typical Finder question, which
    alone would end the demo after one answer), and not the claim checking
    afterwards (a call per claim, plus research, up to ~40k on a turn). Both
    are the product showing its work, and charging the visitor for them
    would close the demo before any of that work had been seen. They are
    still counted, in full, against the address and the daily ceiling - the
    counters that exist to bound what this costs.

    The visitor's side is estimated from its length rather than metered,
    because it is metered only as part of an input that also carries the
    sources. Four characters a token is the usual rule for English, and the
    precision this needs is "about right".
    """
    written = len(message) + sum(len(t["content"]) for t in turns)
    return int(output_tokens) + (written + 3) // 4


def _budget_event(used: int) -> dict:
    return {
        "event": "budget",
        "data": json.dumps(
            {
                "used": used,
                "budget": SESSION_BUDGET,
                # The client shows the sign-up wall on this rather than
                # counting for itself - the number that matters is the one
                # the server charged.
                "limit_reached": used >= SESSION_BUDGET,
            }
        ),
    }


async def _limit_reached() -> AsyncIterator[dict]:
    yield _budget_event(SESSION_BUDGET)


#: What a demo conversation can be at the outside. The session budget is
#: 5,000 tokens, so a real one is far below both of these - they are here so
#: a hand-rolled request cannot post a novel into somebody's workspace.
_MAX_IMPORT_TURNS = 40
_MAX_IMPORT_CHARS = 60_000


class ImportedImage(BaseModel):
    """A picture the demo drew. The pointer only - the bytes are already in
    storage under the visitor's session id, and the URL is the capability
    (see api/images.py), so carrying it across loses nothing."""

    id: uuid.UUID
    owner: uuid.UUID
    prompt: str = Field(default="", max_length=1000)


class ImportTurn(BaseModel):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=MAX_MESSAGE_CHARS * 8)
    # What the answer looked like, so the copy in the account reads the way
    # the demo did: the gist card, the verdict box, the picture. The mode is
    # per turn because smart switching moves a demo conversation between
    # companions. All optional - an older stash carries none of them.
    mode: str | None = None
    crux_text: str | None = Field(default=None, max_length=1000)
    decision_review: dict | None = None
    thinking_review: dict | None = None
    generated_image: ImportedImage | None = None
    #: The support card the demo showed. Only its level, kind and country are
    #: read - the numbers are rebuilt here from the verified table, never
    #: taken from the browser.
    safety: dict | None = None


def _rebuilt_card(raw: dict | None) -> dict | None:
    if not isinstance(raw, dict):
        return None
    level, kind = raw.get("level"), raw.get("kind")
    if level not in ("concern", "crisis") or kind not in safety.KINDS:
        return None
    country = raw.get("country") if isinstance(raw.get("country"), str) else None
    return safety.card(safety.Assessment(level=level, kind=kind), safety.for_turn(country))


class ImportRequest(BaseModel):
    mode: str
    turns: list[ImportTurn] = Field(min_length=1, max_length=_MAX_IMPORT_TURNS)


class ImportResult(BaseModel):
    conversation_id: uuid.UUID
    workspace_id: uuid.UUID
    message_count: int


@router.post("/import", response_model=ImportResult, status_code=status.HTTP_201_CREATED)
async def import_guest_conversation(
    payload: ImportRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> ImportResult:
    """Keep the demo conversation, now that there is an account to keep it in.

    The transcript comes from the browser because that is the only place it
    ever existed - see the module docstring. So this endpoint trusts the
    caller about what was said, which is fine: they are writing into their
    own workspace, and the worst they can do is author their own history.
    The caps above are the real guard, and they are generous enough that a
    genuine demo never meets them.

    The gist, the verdict box and any picture come across, so the copy in
    the account reads as the demo did. The claim checking does not: it was
    computed on our side and its result is posted back by the browser, and a
    verification badge is the one thing in the product that must never be
    something a client can write. The answers are saved unscored.
    """
    # A demo conversation saved before Mentoring and Reflect & Relieve became
    # Guidance still carries the old names - sitting in a visitor's browser
    # until they sign up, which can be weeks later. It imports as Guidance.
    payload_mode = current_mode(payload.mode)
    if payload_mode not in MODE_INSTRUCTIONS or payload_mode == "rapid":
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail="Unknown mode"
        )
    # Health conversations from the demo stay in the demo. Carrying them into
    # an account would store health information that was given before any
    # consent to storing it - Healthcare asks for that consent in the app,
    # and the person can ask again there.
    payload.turns = [
        t for t in payload.turns if (current_mode(t.mode) or payload_mode) != "healthcare"
    ]
    if not payload.turns:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail="Health conversations from the demo are not carried into an account.",
        )

    # The reviews are free-form JSON from the browser; they count towards
    # the same ceiling as the text, so a hand-rolled request cannot use them
    # to post a novel by another route.
    total = sum(
        len(t.content)
        + len(json.dumps(t.decision_review or {}))
        + len(json.dumps(t.thinking_review or {}))
        for t in payload.turns
    )
    if total > _MAX_IMPORT_CHARS:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail="That conversation is too long to import.",
        )

    # Their first workspace - registration makes one, so there is normally
    # exactly this. Ordered rather than "any", so an account with several
    # gets the one it started with instead of whichever the planner returned.
    workspace_id = (
        await db.execute(
            select(Workspace.id)
            .join(WorkspaceMember, WorkspaceMember.workspace_id == Workspace.id)
            .where(WorkspaceMember.user_id == current_user.id)
            .order_by(Workspace.created_at)
            .limit(1)
        )
    ).scalar_one_or_none()
    if workspace_id is None:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="This account has no workspace to import into.",
        )

    first_question = next((t.content for t in payload.turns if t.role == "user"), "")
    first_answer = next((t.content for t in payload.turns if t.role == "assistant"), None)
    fallback = (first_question[:60] or "Saved from the demo").strip()

    conversation = Conversation(
        workspace_id=workspace_id,
        title=await name_conversation(first_question, first_answer, fallback),
        default_mode=payload_mode,
    )
    db.add(conversation)
    await db.flush()

    # Chained, not just ordered. The thread is a tree and every reader of it
    # walks parent links - a flat set of rows with no parents renders as a
    # conversation of one message, which is the whole import lost in the one
    # place it is supposed to have landed.
    parent_id: uuid.UUID | None = None
    saved: list[Message] = []
    for turn in payload.turns:
        turn_mode = current_mode(turn.mode)
        if turn_mode not in MODE_INSTRUCTIONS:
            turn_mode = payload_mode
        assistant = turn.role == "assistant"
        message = Message(
            conversation_id=conversation.id,
            parent_id=parent_id,
            role=turn.role,
            content=clean_output(turn.content),
            mode_used=turn_mode,
            crux_text=clean_output(turn.crux_text) if assistant and turn.crux_text else None,
            decision_review=turn.decision_review if assistant else None,
            thinking_review=turn.thinking_review if assistant else None,
            generated_image=(
                turn.generated_image.model_dump(mode="json")
                if assistant and turn.generated_image
                else None
            ),
            safety=_rebuilt_card(turn.safety) if assistant else None,
        )
        db.add(message)
        await db.flush()
        parent_id = message.id
        saved.append(message)

    conversation.active_leaf_id = saved[-1].id
    await db.commit()

    logger.info(
        "imported a guest conversation of %d messages for user %s",
        len(saved),
        current_user.id,
    )
    return ImportResult(
        conversation_id=conversation.id,
        workspace_id=workspace_id,
        message_count=len(saved),
    )
